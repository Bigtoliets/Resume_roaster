def render(template: str, **variables: Any) -> str:
    """`{{KEY}}` → 值的纯字符串替换。未提供的占位符原样保留（便于发现漏传）。"""
    body = template
    for key, value in variables.items():
        body = body.replace("{{" + key + "}}", str(value))
    return body
